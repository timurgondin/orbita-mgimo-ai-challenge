/**
 * Наполнение пройденного курса. Работы строятся из элементов формулы: «Домашние задания» — пять ДЗ около итогового балла элемента,
 * «Контрольная» — одна работа с отзывом, «Экзамен» — билет из двух вопросов по темам.
 */
export function pastContent(
  title: string,
  comps: [string, number][],
  scores: number[],
  closedAt: Date,
  semesterStart: Date,
  assessment: "exam" | "credit",
): PastContent {
  const r = rng(title + closedAt.toISOString());
  const topics = TOPICS[title] ?? ["Введение", "Основные понятия", "Методы", "Практика", "Итоговое занятие"];
  const lang = /язык/i.test(title);
  const project = comps.some(([t]) => t === "Проект");

  const materials: PastMaterial[] = [];
  const week = (i: number) => addDays(semesterStart, 7 + i * 12);
  topics.forEach((t, i) => {
    if (!lang && !project) {
      const slides = 18 + Math.floor(r() * 22);
      materials.push({
        title: `Лекция ${i + 1}. ${t}`,
        kind: "slides",
        meta: `${slides} слайдов`,
        size: Math.round((1.2 + r() * 3.4) * 1_000_000),
        group: "Лекции",
        plan: [t, ...topics.filter((_, j) => j !== i).slice(0, 2).map((x) => `Связь с темой «${x}»`), "Вопросы для самопроверки"],
      });
    }
  });
  if (!lang && !project && r() > 0.3) {
    materials.push({ title: "Записи лекций", kind: "video", meta: `${topics.length} записей, по 1 ч 20 мин`, group: "Лекции" });
  }
  if (lang) {
    topics.forEach((t, i) =>
      materials.push({ title: `Unit ${i + 1}. ${t}`, kind: "pdf", meta: `${6 + Math.floor(r() * 6)} стр., аудио`, size: Math.round((0.8 + r() * 2) * 1_000_000), group: "Занятия", plan: [t, "Vocabulary", "Reading", "Speaking task"] }),
    );
  } else if (project) {
    materials.push({ title: "Требования к проекту", kind: "doc", meta: "6 стр.", size: 210_000, group: "Проект", plan: ["Тема и цель", "Этапы и сроки", "Критерии оценки", "Защита"] });
    materials.push({ title: "Шаблон отчёта", kind: "doc", meta: "DOCX", size: 64_000, group: "Проект" });
    materials.push({ title: "Пример сильного проекта прошлых лет", kind: "pdf", meta: "22 стр.", size: 2_300_000, group: "Проект", plan: ["Постановка задачи", "Данные", "Результаты", "Выводы"] });
  } else {
    materials.push({
      title: comps.some(([t]) => /Домашн|Контрольн/.test(t)) ? "Задачи к семинарам" : "Планы семинаров",
      kind: "pdf",
      meta: `${24 + Math.floor(r() * 30)} стр.`,
      size: Math.round((0.6 + r()) * 1_000_000),
      group: "Семинары",
      plan: topics.slice(0, 4).map((t, i) => `Семинар ${i + 1}: ${t}`),
    });
    if (r() > 0.4) materials.push({ title: "Данные для практических заданий", kind: "data", meta: "XLSX, 4 листа", size: 860_000, group: "Семинары" });
  }
  if (assessment === "exam") {
    materials.push({ title: "Вопросы к экзамену", kind: "pdf", meta: `${topics.length * 3} вопросов`, size: 180_000, group: "К экзамену", plan: topics.map((t) => t) });
    materials.push({ title: "Демоверсия экзамена с решениями", kind: "pdf", meta: "8 стр.", size: 420_000, group: "К экзамену", plan: ["Задание 1 — теория", "Задание 2 — задача", "Задание 3 — задача", "Критерии оценивания"] });
  }

  const works: PastWork[] = [];
  comps.forEach(([t, w], ci) => {
    const s = scores[ci];
    const clamp = (x: number) => Math.max(4, Math.min(10, Math.round(x)));
    if (/^Домашн/.test(t)) {
      for (let i = 0; i < 5; i++) {
        const sc = clamp(s + (r() - 0.5) * 2.4);
        works.push({ title: `Домашнее задание ${i + 1}`, kind: "homework", score: sc, date: iso(week(i * 1.4)), file: `dz${i + 1}.pdf`, ...(i === 2 && { feedback: sc >= 8 ? FEEDBACK_GOOD[i % 5] : FEEDBACK_MID[i % 5] }) });
      }
    } else if (/^Контрольн/.test(t)) {
      works.push({ title: t, kind: "test", score: s, date: iso(week(ci === 1 ? 3 : 5)), feedback: s >= 8 ? FEEDBACK_GOOD[(ci + Math.floor(r() * 5)) % 5] : FEEDBACK_MID[(ci + Math.floor(r() * 5)) % 5] });
    } else if (t === "Эссе") {
      const topic = topics[Math.floor(r() * topics.length)];
      works.push({ title: `Эссе «${topic}»`, kind: "essay", score: s, date: iso(week(4)), file: "esse.docx", feedback: s >= 8 ? FEEDBACK_GOOD[Math.floor(r() * 5)] : FEEDBACK_MID[Math.floor(r() * 5)] });
    } else if (t === "Writing") {
      works.push({ title: "Opinion essay", kind: "essay", score: s, date: iso(week(2)), file: "essay.pdf", feedback: s >= 8 ? "Clear argument, good linking words" : "Watch the articles and tenses" });
      works.push({ title: "Formal email", kind: "essay", score: clamp(s + (r() - 0.5) * 2), date: iso(week(4)), file: "email.pdf" });
    } else if (t === "Speaking") {
      works.push({ title: "Presentation", kind: "speaking", score: s, date: iso(week(5)), feedback: s >= 8 ? "Confident delivery" : "Slow down and keep eye contact" });
    } else if (t === "Проект") {
      works.push({ title: `Проект «${topics.at(-1)}»`, kind: "project", score: s, date: iso(week(6)), file: "project.zip", feedback: s >= 9 ? "Сильный проект, можно развивать в курсовую" : "Хорошая идея, не хватило глубины анализа" });
    } else if (t === "Защита") {
      works.push({ title: "Защита проекта", kind: "defense", score: s, date: iso(addDays(closedAt, -2)) });
    } else if (t === "Итоговая работа") {
      works.push({ title: "Итоговая работа", kind: "essay", score: s, date: iso(addDays(closedAt, -5)), file: "final.pdf", feedback: s >= 8 ? FEEDBACK_GOOD[Math.floor(r() * 5)] : FEEDBACK_MID[Math.floor(r() * 5)] });
    }
    void w;
  });

  let exam: PastContent["exam"];
  const examIdx = comps.findIndex(([t]) => t === "Экзамен");
  if (examIdx >= 0) {
    const a = Math.floor(r() * topics.length);
    const b = (a + 1 + Math.floor(r() * (topics.length - 1))) % topics.length;
    const ticket = 1 + Math.floor(r() * 30);
    const s = scores[examIdx];
    exam = {
      title: lang ? "Экзамен: письменная часть и speaking" : `Экзамен, билет №${ticket}`,
      ticket,
      questions: lang ? ["Reading and Use of English", "Writing: opinion essay", `Speaking: ${topics[a]}`] : [topics[a], topics[b], "Задача на применение"],
      note: s >= 9 ? "Полный ответ на оба вопроса, задача решена" : s >= 7 ? "Уверенный ответ, в задаче — арифметическая ошибка" : "Первый вопрос раскрыт, во втором — общие слова",
    };
    works.push({ title: exam.title, kind: "exam", score: s, date: iso(closedAt), feedback: exam.note });
  }

  works.sort((x, y) => x.date.localeCompare(y.date));
  const avg = scores.reduce((s, x) => s + x, 0) / scores.length;
  return {
    annotation: ANNOTATIONS[title] ?? `Курс «${title}»: ${topics.slice(0, 3).map((t) => t.toLowerCase()).join(", ")} и другие темы.`,
    topics,
    materials,
    works,
    exam,
    review: avg >= 8.5 ? REVIEW_TOP[Math.floor(r() * REVIEW_TOP.length)] : REVIEW_MID[Math.floor(r() * REVIEW_MID.length)],
  };
}
